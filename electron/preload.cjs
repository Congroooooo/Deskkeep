const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('deskkeep', {
  state: () => ipcRenderer.invoke('vault:state'),
  setup: (input) => ipcRenderer.invoke('vault:setup', input),
  unlock: (password) => ipcRenderer.invoke('vault:unlock', password),
  recover: (input) => ipcRenderer.invoke('vault:recover', input),
  lock: () => ipcRenderer.invoke('vault:lock'),
  list: (type) => ipcRenderer.invoke('data:list', type),
  save: (type, data) => ipcRenderer.invoke('data:save', type, data),
  remove: (type, id) => ipcRenderer.invoke('data:remove', type, id),
  get: (type, id) => ipcRenderer.invoke('data:get', type, id),
  revealCredential: (id) => ipcRenderer.invoke('credential:reveal', id),
  copyCredential: (id, seconds) => ipcRenderer.invoke('credential:copy', id, seconds),
  generate: (options) => ipcRenderer.invoke('password:generate', options),
  copy: (text, seconds) => ipcRenderer.invoke('clipboard:copy', text, seconds),
  exportBackup: () => ipcRenderer.invoke('backup:export'),
  restoreBackup: (masterPassword) => ipcRenderer.invoke('backup:restore', masterPassword),
  exportCsv: () => ipcRenderer.invoke('csv:export'),
  csvTemplate: () => ipcRenderer.invoke('csv:template'),
  inspectCsv: () => ipcRenderer.invoke('csv:inspect'),
  commitCsv: () => ipcRenderer.invoke('csv:commit'),
  exportIncomeCsv: () => ipcRenderer.invoke('income:export-csv'),
  importBook: () => ipcRenderer.invoke('book:import'),
  exportBook: (id) => ipcRenderer.invoke('book:export', id),
  readBook: (id) => ipcRenderer.invoke('book:read', id),
  calendarFeeds: () => ipcRenderer.invoke('calendar:feeds'),
  addCalendarFeed: (input) => ipcRenderer.invoke('calendar:feed-add', input),
  importCalendarFile: (label) => ipcRenderer.invoke('calendar:import-ics', { label }),
  removeCalendarFeed: (id) => ipcRenderer.invoke('calendar:feed-remove', id),
  syncCalendars: () => ipcRenderer.invoke('calendar:sync'),
  calendarEvents: () => ipcRenderer.invoke('calendar:events'),
  getSettings: () => ipcRenderer.invoke('settings:get'),
  updateSettings: (input) => ipcRenderer.invoke('settings:update', input),
  updateProfile: (name) => ipcRenderer.invoke('profile:update', name),
  changeMasterPassword: (input) => ipcRenderer.invoke('security:change-password', input),
  rotateRecovery: () => ipcRenderer.invoke('security:rotate-recovery'),
  clearActivity: () => ipcRenderer.invoke('activity:clear'),
  chooseAvatar: () => ipcRenderer.invoke('profile:choose-avatar'),
  websiteIcon: (website) => ipcRenderer.invoke('website:icon', website),
  importMarkdown: () => ipcRenderer.invoke('note:import-md'),
  reset: (phrase) => ipcRenderer.invoke('vault:reset', phrase),
  onLocked: (callback) => { const listener = () => callback(); ipcRenderer.on('vault:locked', listener); return () => ipcRenderer.off('vault:locked', listener); }
});
